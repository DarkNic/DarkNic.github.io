import {
  createContext,
  useContext,
  useEffect,
  useState,
  type ReactNode,
} from "react";

type Theme = "light" | "dark";

interface ThemeContextType {
  theme: Theme;
  toggleTheme: () => void;
}

const ThemeContext = createContext<ThemeContextType | undefined>(undefined);

interface ThemeProviderProps {
  children: ReactNode;
}

export function ThemeProvider({ children }: ThemeProviderProps) {
  const [theme, setTheme] = useState<Theme>(() => {
    const consent = localStorage.getItem("cookieConsent");
    if (consent === "rejected") return "dark"; //Options: fun, accepted, rejected

    const savedTheme = localStorage.getItem("backgroundTheme");
    if (savedTheme === "light" || savedTheme === "dark") return savedTheme;

    //TODO: look into this call
    return window.matchMedia("(prefers-color-scheme: dark)").matches
      ? "dark"
      : "light";
  });

  useEffect(() => {
    document.documentElement.setAttribute("data-theme", theme);
    const consent = localStorage.getItem("cookieConsent");
    if (consent !== "rejected") {
      localStorage.setItem("backgroundTheme", "dark");
    } else {
      localStorage.setItem("backgroundTheme", theme);
    }
  }, [theme]);

  const toggleTheme = () => {
    setTheme((currentTheme) => (currentTheme === "light" ? "dark" : "light"));
  };

  return (
    <ThemeContext.Provider 
        value={{ theme, toggleTheme }}
    >
      {children}
    </ThemeContext.Provider>
  );
}

export function useTheme() {
  const context = useContext(ThemeContext);

  if (!context) {
    throw new Error("useTheme must be used within a ThemeProvider");
  }

  return context;
}
